package sqlite

import (
	"context"
	"errors"
	"math"
	"path/filepath"
	"strings"
	"time"
)

type config struct {
	library    string
	bundled    bool
	busyMS     int32
	readOnly   bool
	wal        bool
	txMode     string
	extensions bool
	init       func(context.Context, *Conn) error
	pragmas    []string
	journal    string
	parseTime  bool
	parseBool  bool
	mattnTypes bool
	location   *time.Location
}

// Option configures every physical connection created by a Connector.
type Option func(*config) error

// WithLibrary selects an explicitly trusted absolute native library path.
func WithLibrary(path string) Option {
	return func(c *config) error {
		if !filepath.IsAbs(path) || strings.ContainsRune(path, 0) {
			return errors.New("sqlite: library path must be absolute and contain no NUL")
		}
		c.library = filepath.Clean(path)
		return nil
	}
}

// WithBundled uses the platform asset generated by go run ./internal/cmd/build-native --embed.
// An explicit WithLibrary takes precedence, independent of option order.
func WithBundled() Option { return func(c *config) error { c.bundled = true; return nil } }
func WithBusyTimeout(timeout time.Duration) Option {
	return func(c *config) error {
		if timeout < 0 || timeout.Milliseconds() > math.MaxInt32 {
			return errors.New("sqlite: busy timeout out of range")
		}
		c.busyMS = int32(timeout.Milliseconds())
		return nil
	}
}
func WithReadOnly() Option { return func(c *config) error { c.readOnly = true; return nil } }
func WithWAL() Option      { return func(c *config) error { c.wal = true; c.journal = "WAL"; return nil } }

// WithMattnTypes opts into mattn-compatible DATE/DATETIME/TIMESTAMP and BOOLEAN
// decoding and declaration metadata. Without it, result storage classes remain
// unchanged. Invalid date strings decode to zero time, as in mattn.
func WithMattnTypes() Option {
	return func(c *config) error { c.parseTime, c.parseBool, c.mattnTypes = true, true, true; return nil }
}

// WithTimeLocation enables declared date/time decoding in the given location.
// Offset-free stored timestamps are interpreted as UTC before conversion.
func WithTimeLocation(location *time.Location) Option {
	return func(c *config) error {
		if location == nil {
			return errors.New("sqlite: nil time location")
		}
		c.parseTime, c.location = true, location
		return nil
	}
}

// WithBooleanConversion decodes INTEGER values in BOOLEAN columns as bool.
func WithBooleanConversion() Option {
	return func(c *config) error { c.parseBool = true; return nil }
}

// WithTransactionMode chooses DEFERRED (default), IMMEDIATE or EXCLUSIVE.
func WithTransactionMode(mode string) Option {
	return func(c *config) error {
		mode = strings.ToUpper(mode)
		switch mode {
		case "DEFERRED", "IMMEDIATE", "EXCLUSIVE":
			c.txMode = mode
			return nil
		}
		return errors.New("sqlite: invalid transaction mode")
	}
}

// WithExtensions opts in to trusted C API extension loading. SQL loading stays disabled.
func WithExtensions() Option { return func(c *config) error { c.extensions = true; return nil } }

// WithInit runs before each connection enters the pool. Close all rows/statements
// before returning, and do not retain Conn or start goroutines using it.
func WithInit(fn func(context.Context, *Conn) error) Option {
	return func(c *config) error { c.init = fn; return nil }
}
