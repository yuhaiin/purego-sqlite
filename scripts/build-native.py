#!/usr/bin/env python3
"""Build pinned official SQLite, a local test extension, and optional embed data.

This uses a C compiler at asset build time; the Go driver still needs no CGO.
No third-party executable is downloaded. Requires Python 3 and cc/clang.
"""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import shlex
import subprocess
import urllib.request
import zipfile

VERSION = "3.54.1"
ARCHIVE = "sqlite-amalgamation-3540100.zip"
URL = "https://www.sqlite.org/2026/" + ARCHIVE
SHA256 = "0a9c8e34352dad46006aa82836d5383bff9dc6bc9ce5a60553c05aa30e6ad1f9"
# Published by https://www.sqlite.org/download.html, checked before pinning SHA256.
SHA3_256 = "92281c86e2957f9b9305890f9ac04204caa7b677cc868dc326d942689df28e30"
FLAGS = ["-DSQLITE_THREADSAFE=1", "-DSQLITE_ENABLE_FTS5", "-DSQLITE_ENABLE_RTREE",
         "-DSQLITE_ENABLE_DBSTAT_VTAB", "-DSQLITE_ENABLE_MATH_FUNCTIONS",
         "-DSQLITE_USE_URI=1"]
ROOT = Path(__file__).resolve().parents[1]


def run(args):
    print(shlex.join(str(x) for x in args), flush=True)
    subprocess.run(args, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--embed", action="store_true")
    args = parser.parse_args()
    out = ROOT / ".native"
    out.mkdir(exist_ok=True)
    archive = out / ARCHIVE
    if not archive.exists():
        with urllib.request.urlopen(URL, timeout=60) as response:
            data = response.read()
        if hashlib.sha256(data).hexdigest() != SHA256 or hashlib.sha3_256(data).hexdigest() != SHA3_256:
            raise SystemExit("official SQLite source checksum mismatch")
        archive.write_bytes(data)
    data = archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256 or hashlib.sha3_256(data).hexdigest() != SHA3_256:
        raise SystemExit("cached SQLite source checksum mismatch")
    source = out / "src"
    source.mkdir(exist_ok=True)
    # Extract only explicitly named files, without archive-controlled paths.
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for filename in ("sqlite3.c", "sqlite3.h", "sqlite3ext.h"):
            (source / filename).write_bytes(z.read("sqlite-amalgamation-3540100/" + filename))
    goos = {"Linux": "linux", "Darwin": "darwin", "Windows": "windows"}[platform.system()]
    arch = {"x86_64": "amd64", "AMD64": "amd64", "aarch64": "arm64", "arm64": "arm64", "ARM64": "arm64"}[platform.machine()]
    compiler = shlex.split(os.environ.get("CC", "clang" if goos == "windows" else "cc"))
    filename = {"linux": "libsqlite3.so", "darwin": "libsqlite3.dylib", "windows": "sqlite3.dll"}[goos]
    extension = "test_extension.dll" if goos == "windows" else "test_extension.so"
    shared = ["-dynamiclib"] if goos == "darwin" else ["-shared"]
    common = ["-O2"] + shared
    if goos != "windows":
        common += ["-fPIC"]
    libs = ["-lm", "-lpthread", "-ldl"] if goos == "linux" else (["-lm", "-lpthread"] if goos == "darwin" else [])
    flags = FLAGS + (["-DSQLITE_API=__declspec(dllexport)"] if goos == "windows" else [])
    run(compiler + common + flags + [str(source / "sqlite3.c"), "-o", str(out / filename)] + libs)
    run(compiler + common + ["-I" + str(source), str(ROOT / "tests/testdata/extension.c"), "-o", str(out / extension)])
    digest = hashlib.sha256((out / filename).read_bytes()).hexdigest()
    manifest = {"sqlite": VERSION, "source": URL, "source_sha256": SHA256,
                "source_sha3_256": SHA3_256, "library_sha256": digest,
                "goos": goos, "goarch": arch, "flags": flags,
                "compiler": subprocess.check_output(compiler + ["--version"], text=True).splitlines()[0]}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    if args.embed:
        assets = ROOT / "internal/native/assets"
        assets.mkdir(exist_ok=True)
        assetname = goos + "_" + arch + "_" + filename
        (assets / assetname).write_bytes((out / filename).read_bytes())
        generated = ROOT / ("internal/native/asset_" + goos + "_" + arch + ".go")
        generated.write_text(f'''// Code generated by scripts/build-native.py; DO NOT EDIT.
//go:build sqlite_bundle && {goos} && {arch}

package native

import _ "embed"

//go:embed assets/{assetname}
var platformAsset []byte

func init() {{
 asset = platformAsset
 digest = "{digest}"
 filename = "{filename}"
}}
''')
        run(["gofmt", "-w", str(generated)])
    print("Native build manifest: " + str(out / "manifest.json"))


if __name__ == "__main__":
    main()
